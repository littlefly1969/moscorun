import assert from "node:assert/strict";
import {auditSeries,causalAlign,validateObservation,validateFeedback,buildContext,chronologicalSplit,athleteHoldout,persistenceReplay} from "./core.mjs";
export async function runChecks(){
  let checks=0;const check=f=>{f();checks++;};
  check(()=>assert.equal(auditSeries([{time:0,value:100},{time:1000,value:110},{time:11000,value:120}],{start:0,end:11000,maxGapMs:2000}).timeWeightedMean,(100*1000+110*2000)/3000));
  check(()=>assert.equal(auditSeries([{time:0,value:0},{time:1000,value:2}],{start:0,end:1000}).timeWeightedMean,0));
  check(()=>assert.equal(auditSeries([{time:0,value:1},{time:0,value:2}]).validCount,0));
  check(()=>assert.equal(auditSeries([{time:0,value:null},{time:1,value:NaN}]).invalidCount,2));
  check(()=>assert.equal(auditSeries([{time:0,value:1}]).coverage,0));
  check(()=>assert.equal(causalAlign([{time:1000,value:10}], [999])[0].value,null));
  check(()=>assert.equal(causalAlign([{time:1000,value:10}], [11000],{maxAgeMs:2000})[0].value,null));
  check(()=>assert.equal(causalAlign([{time:1000,value:10},{time:1000,value:11}], [1000])[0].value,null));
  const observation={ownerId:"a",metric:"weight",unit:"kg",time:"2026-01-01T00:00:00Z",availableAt:"2026-01-01T00:00:00Z",source:"scale",method:"measured",value:70};
  check(()=>assert.equal(validateObservation(observation,"a"),true));
  check(()=>assert.throws(()=>validateObservation(observation,"b")));
  check(()=>assert.throws(()=>validateObservation({...observation,method:"provider_estimated"},"a")));
  const feedback={ownerId:"a",id:"f1",time:"2026-01-01T01:00:00Z",availableAt:"2026-01-01T01:01:00Z",scale:"moscorun-feedback-v1",rpe:7,pain:0,notes:"untrusted content"};
  check(()=>assert.equal(validateFeedback(feedback,"a"),true));
  check(()=>assert.throws(()=>validateFeedback({...feedback,rpe:11},"a")));
  check(()=>assert.throws(()=>validateFeedback({...feedback,pain:3},"a")));
  const workout={ownerId:"a",id:"w1",revision:1,source:"synthetic",startedAt:"2026-01-01T00:00:00Z",endedAt:"2026-01-01T00:00:01Z",availableAt:"2026-01-01T00:00:02Z",
    series:[{metric:"heartRate",unit:"bpm",availableAt:"2026-01-01T00:00:02Z",samples:[{time:"2026-01-01T00:00:00Z",value:100},{time:"2026-01-01T00:00:01Z",value:110}]}]};
  const dataset={schemaVersion:1,ownerId:"a",workouts:[workout],observations:[observation],feedback:[feedback]};
  const ctx=buildContext(dataset,{ownerId:"a",asOf:"2026-01-01T00:00:03Z"});
  check(()=>assert.equal(ctx.workouts.length,1));
  check(()=>assert.equal(ctx.feedback.length,0));
  check(()=>assert.equal(buildContext(dataset,{ownerId:"a",asOf:"2026-01-01T00:00:01Z"}).workouts.length,0));
  check(()=>assert.throws(()=>buildContext({...dataset,observations:[{...observation,ownerId:"b"}]},{ownerId:"a",asOf:"2026-01-02"})));
  check(()=>assert.equal(JSON.stringify(ctx).includes("latitude"),false));
  check(()=>assert.equal(buildContext(dataset,{ownerId:"a",asOf:"2026-01-01T00:00:03Z"}).contentSha256,ctx.contentSha256));
  const split=chronologicalSplit([workout,{...workout,id:"w2",startedAt:"2026-01-02T00:00:00Z"}]);
  check(()=>assert.deepEqual(split.test.map(w=>w.id),["w2"]));
  check(()=>assert.throws(()=>chronologicalSplit([workout,workout])));
  check(()=>assert.throws(()=>chronologicalSplit([workout,{...workout,id:"w2",ownerId:"b"}])));
  check(()=>assert.equal(athleteHoldout([workout,{...workout,id:"w2",ownerId:"b"}],"b").train.length,1));
  check(()=>assert.equal(persistenceReplay([{time:0,value:100},{time:1000,value:110},{time:2000,value:120}],{horizonMs:1000}).mae,10));
  check(()=>assert.throws(()=>validateObservation({...observation,unit:"lb"},"a")));
  const privateContext=buildContext({...dataset,observations:[{...observation,latitude:42,privateToken:"not-for-context"}]},{ownerId:"a",asOf:"2026-01-02"});
  check(()=>assert.equal(JSON.stringify(privateContext).includes("privateToken"),false));
  check(()=>assert.equal(JSON.stringify(privateContext).includes("latitude"),false));
  check(()=>assert.equal(causalAlign(Array.from({length:10000},(_,i)=>({time:i*1000,value:i})),[9999000])[0].value,9999));
  const withCoordinates=buildContext({...dataset,workouts:[{...workout,series:[...workout.series,{...workout.series[0],metric:"latitude",unit:"deg"}]}]},{ownerId:"a",asOf:"2026-01-02"});
  check(()=>assert.equal(withCoordinates.workouts[0].series.length,1));
  return {checks,status:"passed"};
}
